    """ja が空で en だけのとき、働き方は英語コードで入る（api.py の _flatten_labels）。"""
    assert unwanted_work_conditions("NoRelocation、RemoteWork")
    assert unwanted_work_conditions("NoOvertime")
    assert unwanted_work_conditions("NoBusinessTrip")
    # RemoteWork 単体は「リモート可」相当なので除外しない。
    assert unwanted_work_conditions("RemoteWork") == []


